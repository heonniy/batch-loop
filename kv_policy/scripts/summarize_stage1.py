"""Render Stage-1 parity JSONs into SUMMARY.md (numbers are copied from the receipts, not retyped)."""

from __future__ import annotations

import json
import sys
from pathlib import Path


def main():
    run = Path(sys.argv[1])
    md = ["# Stage 1 summary (generated by scripts/summarize_stage1.py)\n"]
    for f in sorted(run.glob("parity_*.json")):
        r = json.loads(f.read_text())
        s = r["sections"]
        md.append(f"## {r['model']}  (GPU {r['gpu']['name']} {r['gpu']['uuid']}, {r['wall_s']:.0f}s)\n")
        md.append("| check | cases | max abs logit diff | min top-1 agreement | max KL |")
        md.append("|---|---|---|---|---|")
        for key, label in (("a_full_vs_native_fp32", "FULL engine vs native HF, fp32"),
                           ("a_full_vs_native_bf16", "FULL engine vs native HF, bf16"),
                           ("b_policy_engine_vs_reference_fp32", "policy engine vs dict-cache reference, fp32")):
            v = s[key]
            for mode in ("decode", "strict"):
                rows = [x for x in v if x["mode"] == mode]
                if not rows:
                    continue
                md.append(f"| {label} ({mode}) | {len(rows)} | {max(x['max_abs_logit_diff'] for x in rows):.3g} | "
                          f"{min(x['top1_agreement'] for x in rows):.4f} | {max(x['max_kl'] for x in rows):.3g} |")
        md.append("")
        md.append("Policy rows of the reference check (fp32): " + ", ".join(
            f"{x['policy']}/{x['mode']}/{x['case']}={x['max_abs_logit_diff']:.1e}" for x in s["b_policy_engine_vs_reference_fp32"]))
        md.append("")
        md.append("Greedy 48-token generation, bf16 (first divergence index, None = identical):")
        for x in s["c_greedy_native_vs_engine_bf16"]:
            md.append(f"- {x['uid']}: native vs engine B1 = {x['native_vs_engine_b1_first_divergence']}, "
                      f"native vs engine B4 = {x['native_vs_engine_b4_first_divergence']}, "
                      f"engine B1 vs B4 = {x['engine_b1_vs_b4_first_divergence']}")
        md.append("")
        d = s["d_batch_shape_sensitivity_bf16"]
        md.append("bf16 batch-shape sensitivity (B=4 vs B=1, teacher-forced 48 gold tokens): " + ", ".join(
            f"{p}: max |Δlogprob| {max(x['max_abs_logprob_diff_b4_vs_b1'] for x in d if x['policy'] == p):.3f}, "
            f"max |Δsum| {max(abs(x['sum_logprob_b1'] - x['sum_logprob_b4']) for x in d if x['policy'] == p):.3f}"
            for p in ("full", "last", "average")))
        md.append("")
    for name in ("pytest_cpu.log", "pytest_cpu_final.log"):
        log = run / name
        if log.exists():
            text = log.read_text().strip().splitlines()
            sha = next((ln for ln in text if ln.startswith("source_sha=")), "source_sha=d7a92d0 (run source)")
            md.append(f"CPU tests `{name}` ({sha}): `" + text[-1].strip("= ") + "`")
    (run / "SUMMARY.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
